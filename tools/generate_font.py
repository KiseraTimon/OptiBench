#!/usr/bin/env python3
"""
Generates src/render/FontData.inc: anti-aliased bitmap fonts for OptiBench's text renderer.

The glyphs are rasterised from DejaVu Sans Mono (free licence, see the notice written into the
generated file) at fixed pixel sizes and stored as 4-bit coverage, two pixels per byte.
The build does not need this script: its output is committed. Re-run it only to change the fonts:

    pip install pillow
    python3 tools/generate_font.py [path/to/DejaVuSansMono.ttf] [path/to/DejaVuSansMono-Bold.ttf]
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "render", "FontData.inc")

DEFAULT_DIR = "/usr/share/fonts/truetype/dejavu"
REGULAR = sys.argv[1] if len(sys.argv) > 1 else os.path.join(DEFAULT_DIR, "DejaVuSansMono.ttf")
BOLD = sys.argv[2] if len(sys.argv) > 2 else os.path.join(DEFAULT_DIR, "DejaVuSansMono-Bold.ttf")

# printable ASCII plus the symbols the bench labels use
EXTRA = "°θλ·→×µ≥≤Δ✓✗±–′"
CODEPOINTS = list(range(32, 127)) + [ord(c) for c in EXTRA]

# (C++ identifier, font file, pixel size)
FONTS = [
    ("kSmall", REGULAR, 12),
    ("kRegular", REGULAR, 14),
    ("kTitle", BOLD, 20),
]

LICENSE = """\
// Glyphs rasterised from DejaVu Sans Mono.
// Fonts are (c) Bitstream (see below). DejaVu changes are in public domain.
// Bitstream Vera Fonts Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved. Bitstream Vera is
// a trademark of Bitstream, Inc. Permission is hereby granted, free of charge, to any person obtaining
// a copy of the fonts accompanying this license ("Fonts") and associated documentation files (the
// "Font Software"), to reproduce and distribute the Font Software, including without limitation the
// rights to use, copy, merge, publish, distribute, and/or sell copies of the Font Software, and to
// permit persons to whom the Font Software is furnished to do so, subject to the following conditions:
// The above copyright and trademark notices and this permission notice shall be included in all copies
// of one or more of the Font Software typefaces. The Font Software may be modified, altered, or added
// to, and in particular the designs of glyphs or characters in the Fonts may be modified and additional
// glyphs or characters may be added to the Fonts, only if the fonts are renamed to names not containing
// either the words "Bitstream" or the word "Vera". THE FONT SOFTWARE IS PROVIDED "AS IS", WITHOUT
// WARRANTY OF ANY KIND. (Full text: https://dejavu-fonts.github.io/License.html)
"""


def rasterise(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    advance = round(font.getlength("M"))
    height = ascent + descent
    glyphs = []
    for cp in CODEPOINTS:
        img = Image.new("L", (advance, height), 0)
        ImageDraw.Draw(img).text((0, ascent), chr(cp), font=font, fill=255, anchor="ls")
        px = list(img.tobytes())
        nibbles = [(v * 15 + 127) // 255 for v in px]
        if len(nibbles) % 2:
            nibbles.append(0)
        glyphs.append(bytes((nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2)))
    return advance, height, ascent, glyphs


def main():
    lines = [
        "// GENERATED by tools/generate_font.py: do not edit by hand.",
        "// 4-bit coverage, row-major, two pixels per byte (high nibble first).",
        LICENSE,
        "// clang-format off",
        "namespace ob::render::fontdata {",
        "constexpr char32_t kCodepoints[] = {" + ", ".join(str(c) for c in CODEPOINTS) + "};",
        f"constexpr int kGlyphCount = {len(CODEPOINTS)};",
        "",
    ]
    for name, path, size in FONTS:
        advance, height, ascent, glyphs = rasterise(path, size)
        per = len(glyphs[0])
        lines.append(f"// {os.path.basename(path)} at {size} px: cell {advance} x {height}, ascent {ascent}")
        lines.append(f"constexpr int {name}Advance = {advance}, {name}Height = {height}, {name}Ascent = {ascent};")
        lines.append(f"constexpr int {name}BytesPerGlyph = {per};")
        lines.append(f"constexpr unsigned char {name}Data[] = {{")
        for g in glyphs:
            lines.append("    " + ",".join(f"0x{b:02x}" for b in g) + ",")
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace ob::render::fontdata")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(CODEPOINTS)} glyphs x {len(FONTS)} fonts)")


if __name__ == "__main__":
    main()
